function normalizeLangCode(lang: string): string {
  const norm = lang.trim().toLowerCase().replace(/_/, '-');
  if (norm.startsWith('ewo')) return 'ewo';
  if (norm.startsWith('fuv') || norm.startsWith('fub')) return 'fuv';
  if (norm.startsWith('hau')) return 'hau';
  if (norm.startsWith('knc')) return 'knc';
  if (norm.startsWith('pcm')) return 'pcm';
  if (norm.startsWith('dua')) return 'dua';
  return norm;
}

export function translateSentenceToSovereign(
  text: string,
  targetLang: string
): { translatedText: string; status: 'success' | 'unverified'; warnings: string[] } {
  const normLang = normalizeLangCode(targetLang);

  if (normLang === 'ewo') {
    const translatedText = translateSentenceToEwondo(text);
    return {
      translatedText,
      status: translatedText === text ? 'unverified' : 'success',
      warnings: translatedText === text ? ['EWONDO_NO_MATCH'] : [],
    };
  }

  if (normLang === 'dua') {
    return {
      translatedText: text,
      status: 'unverified',
      warnings: ['DUALA_QUARANTINED_UNVERIFIED', 'DUALA_NO_VERIFIED_TRANSLATION'],
    };
  }

  const dict = SOVEREIGN_DICTIONARIES[normLang];
  if (!dict) {
    return {
      translatedText: text,
      status: 'unverified',
      warnings: [`UNSUPPORTED_LANGUAGE_${targetLang}`],
    };
  }

  const trimmed = text.trim();
  if (!trimmed) {
    return { translatedText: text, status: 'unverified', warnings: [] };
  }

  // 1. Guard financial entities with placeholder tokens
  const { guardedText, entities } = extractAndGuardEntities(trimmed);

  // 2. Multi-word phrase substitution (sorted by descending length)
  let workingText = guardedText;
  const multiWordKeys = Object.keys(dict)
    .filter((k) => k.includes(' ') || k.includes("'"))
    .sort((a, b) => b.length - a.length);

  let matched = false;
  for (const phrase of multiWordKeys) {
    const targetTerm = dict[phrase];
    const escaped = escapeRegExp(phrase);
    const regex = new RegExp(`(^|[^\\p{L}\\p{N}])(${escaped})([^\\p{L}\\p{N}]|$)`, 'giu');
    if (regex.test(workingText)) {
      matched = true;
      workingText = workingText.replace(regex, (match, prefix, captured, suffix) => {
        let replacement = targetTerm;
        if (captured === captured.toUpperCase() && captured.length > 1) {
          replacement = targetTerm.toUpperCase();
        } else if (captured[0] === captured[0].toUpperCase()) {
          replacement = targetTerm.charAt(0).toUpperCase() + targetTerm.slice(1);
        }
        return `${prefix}${replacement}${suffix}`;
      });
    }
  }

  // 3. Token-by-token single word substitution (matching website UI elements, buttons, titles)
  const tokens = workingText.split(/(\s+|[,;:.!?()\/\\'\-–—«»""→←↑↓·•|]|<\/?t\d+>|⟦T\d+:|⟧)/u);
  const translatedTokens: string[] = [];

  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];
    if (!token) continue;

    // Direct single word or mapped digit/number lookup
    const wordKey = token.toLowerCase();
    const wordMatch = dict[wordKey];
    if (wordMatch) {
      matched = true;
      let repl = wordMatch;
      if (token === token.toUpperCase() && token.length > 1) {
        repl = wordMatch.toUpperCase();
      } else if (token[0] === token[0].toUpperCase()) {
        repl = wordMatch.charAt(0).toUpperCase() + wordMatch.slice(1);
      }
      translatedTokens.push(repl);
      continue;
    }

    // Preserve whitespace, punctuation, entity placeholders, tag placeholders, unmapped pure numbers
    if (/^(\s+|[,;:.!?()\/\\'\-–—«»""])$/.test(token) ||
        /^___FIN_GUARD_\d+___$/.test(token) ||
        /^<\/?t\d+>$/.test(token) ||
        /^⟦T\d+:$/.test(token) ||
        token === '⟧' ||
        /^[\d\s.,\u00a0]+$/.test(token) ||
        /^(FCFA|XAF|CFA|EUR|USD|XOF)$/i.test(token)) {
      translatedTokens.push(token);
      continue;
    }

    // French elision prefix handling (d', l', c', s', n', qu')
    if (/^[ldcsqnjm]['’]$/i.test(token) && i + 1 < tokens.length) {
      let nextIdx = i + 1;
      while (nextIdx < tokens.length && !tokens[nextIdx].trim()) nextIdx++;
      if (nextIdx < tokens.length) {
        const nextWord = tokens[nextIdx];
        const nextLookup = dict[nextWord.toLowerCase()];
        if (nextLookup) {
          matched = true;
          let repl = nextLookup;
          if (nextWord === nextWord.toUpperCase() && nextWord.length > 1) {
            repl = nextLookup.toUpperCase();
          } else if (token[0] === token[0].toUpperCase()) {
            repl = nextLookup.charAt(0).toUpperCase() + nextLookup.slice(1);
          }
          translatedTokens.push(repl);
          i = nextIdx;
          continue;
        }
      }
    }

    // Unmatched token fallback
    translatedTokens.push(token);
  }

  let finalWorking = translatedTokens.join('');

  // 4. Restore guarded entities with absolute fidelity
  for (const ent of entities) {
    finalWorking = finalWorking.split(ent.placeholder).join(ent.raw);
  }

  return {
    translatedText: finalWorking,
    status: matched ? 'success' : 'unverified',
    warnings: matched ? [] : ['NO_DIRECT_TERM_MATCH'],
  };
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
